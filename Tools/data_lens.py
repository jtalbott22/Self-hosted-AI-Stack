def _v_tables(tables: list[dict], limit_rows: int, max_tables: int = 3) -> str:
    parts = []
    for t in tables[:max_tables]:
        headers, rows = t["headers"], t["rows"][:limit_rows]
        width = max(len(r) for r in rows)
        if headers:
            head = "".join(f"<th>{_e(h)}</th>" for h in headers[:width])
        else:
            head = "".join(f"<th>C{i+1}</th>" for i in range(min(width, 12)))
        body = []
        for r in rows:
            tds = "".join(_td(c) for c in r[:12])
            body.append(f"<tr>{tds}</tr>")
        cap = f'<div class="tcap">{_e(t["caption"])}</div>' if t["caption"] else ""
        hidden = len(t["rows"]) - len(rows)
        more = (
            f'<p class="more">{hidden} more rows on the source page.</p>'
            if hidden > 0
            else ""
        )
        parts.append(
            f'{cap}<div class="scroll"><table><thead><tr>{head}</tr></thead>'
            f'<tbody>{"".join(body)}</tbody></table></div>{more}'
        )
    return "".join(parts)


