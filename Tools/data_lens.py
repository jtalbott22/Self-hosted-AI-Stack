def _url_block_reason(url: str, allow_private: bool) -> Optional[str]:
    p = urlparse(url)
    if p.scheme not in ("http", "https"):
        return f"Only http/https URLs are allowed (got “{p.scheme or 'none'}”)."
    if not p.hostname:
        return "That URL has no hostname."
    if allow_private:
        return None
    try:
        infos = socket.getaddrinfo(p.hostname, None)
    except socket.gaierror:
        return f"Could not resolve host “{p.hostname}”."
    for info in infos:
        ip = ipaddress.ip_address(info[4][0])
        if ip.is_private or ip.is_loopback or ip.is_link_local or ip.is_reserved:
            return (
                f"“{p.hostname}” resolves to a private address ({ip}). "
                "Enable ALLOW_PRIVATE_NETWORKS in the tool valves to browse "
                "internal hosts."
            )
    return None


