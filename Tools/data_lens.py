def _e(v: Any) -> str:
    return _html.escape("" if v is None else str(v), quote=True)


_NUM_RE = re.compile(r"^[\s$€£+-]*[\d.,]+\s*(%|[A-Za-z]{0,3})\s*$")


def _numeric(s: Any) -> bool:
    return bool(_NUM_RE.match(str(s).strip())) if s not in (None, "") else False


def _host(url: str) -> str:
    try:
        return urlparse(url).netloc.replace("www.", "")
    except Exception:
        return ""


def _clip(s: str, n: int) -> str:
    s = " ".join(str(s).split())
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


_YEAR_RE = re.compile(r"(?<!\d)(19\d{2}|20\d{2})(?!\d)")


def _freshen(query: str) -> tuple[str, str]:
    """Drop recent-but-stale years from a search query.

    Models anchor to their training cutoff and silently stamp a stale year onto
    "current" questions ("macbook pro best price 2024"), which returns stale
    results no matter how fresh the index is.

    Only years inside a training-cutoff-plausible window are touched. A year
    well in the past ("the 1969 moon landing") or in the future is deliberate
    and is left alone. Returns (query, note).
    """
    this_year = time.localtime().tm_year
    window = range(this_year - 6, this_year)  # e.g. 2020..2025 in 2026

    dropped: list[str] = []

    def drop(m):
        if int(m.group()) in window:
            dropped.append(m.group())
            return ""
        return m.group()

    cleaned = " ".join(_YEAR_RE.sub(drop, query).split())
    if not cleaned or cleaned == query:
        return query, ""
    return cleaned, f"dropped stale year {', '.join(sorted(set(dropped)))}"


_JUNK_IMG = re.compile(
    r"(sprite|/icons?/|icon[-_.]|logo|avatar|badge|spacer|pixel|1x1|blank\.|"
    r"placeholder|emoji|favicon|tracking|beacon|\.gif$)",
    re.I,
)

_EMBED_HOSTS = re.compile(
    r"(youtube\.com/embed|youtube-nocookie\.com|player\.vimeo\.com|"
    r"dailymotion\.com/embed|w\.soundcloud\.com|open\.spotify\.com/embed|"
    r"archive\.org/embed|players\.brightcove)",
    re.I,
)


def _pick_srcset(value: str) -> str:
    """Largest candidate from a srcset descriptor list."""
    best, best_w = "", -1.0
    for part in value.split(","):
        bits = part.strip().split()
        if not bits:
            continue
        url = bits[0]
        w = 0.0
        if len(bits) > 1:
            d = bits[1].strip().lower()
            try:
                w = float(d[:-1]) * (1000 if d.endswith("x") else 1)
            except ValueError:
                w = 0.0
        if w >= best_w:
            best, best_w = url, w
    return best


def _media_src(el, base: str) -> str:
    """Resolve an element's real source, accounting for lazy-loading.

    Many sites ship a placeholder in src and the real image in data-src or
    srcset, so reading src alone yields blank boxes.
    """
    for attr in ("data-srcset", "srcset"):
        v = el.get(attr)
        if v:
            picked = _pick_srcset(v)
            if picked:
                return urljoin(base, picked)
    for attr in (
        "data-src",
        "data-original",
        "data-lazy-src",
        "data-hi-res-src",
        "data-image",
        "src",
    ):
        v = (el.get(attr) or "").strip()
        if v and not v.startswith("data:image/gif"):
            return urljoin(base, v)
    return ""


def _img_is_junk(el, url: str) -> bool:
    if not url or url.startswith("data:"):
        return True
    if _JUNK_IMG.search(url):
        return True
    for attr in ("width", "height"):
        try:
            if int(str(el.get(attr, "")).strip().rstrip("px")) < 120:
                return True
        except (ValueError, TypeError):
            pass
    cls = " ".join(el.get("class") or []) + " " + (el.get("id") or "")
    return bool(_JUNK_IMG.search(cls))


def _media_from(el, base: str, seen: set) -> Optional[dict]:
    """Turn an img/figure/video/iframe element into a media block, or None."""
    name = el.name
    if name == "figure":
        inner = el.find(["img", "video"])
        if not inner:
            return None
        item = _media_from(inner, base, seen)
        if item:
            cap = el.find("figcaption")
            if cap:
                item["caption"] = _clip(cap.get_text(" ", strip=True), 220)
        return item

    if name == "img":
        src = _media_src(el, base)
        if _img_is_junk(el, src) or src in seen:
            return None
        seen.add(src)
        return {"kind": "img", "src": src, "caption": _clip(el.get("alt") or "", 220)}

    if name == "video":
        src = _media_src(el, base) or _media_src(el.find("source") or el, base)
        if not src or src in seen:
            return None
        seen.add(src)
        return {"kind": "video", "src": src, "caption": ""}

    if name == "iframe":
        src = urljoin(base, (el.get("src") or el.get("data-src") or "").strip())
        if not src or src in seen or not _EMBED_HOSTS.search(src):
            return None
        seen.add(src)
        return {
            "kind": "embed",
            "src": src,
            "caption": _clip(el.get("title") or "", 220),
        }
    return None


def _hero_image(soup: BeautifulSoup, base: str) -> Optional[dict]:
    """og:image / twitter:image — a decent lead image when a page has no
    inline figures at all."""
    for prop in ("og:image", "twitter:image", "og:image:url"):
        tag = soup.find("meta", property=prop) or soup.find(
            "meta", attrs={"name": prop}
        )
        if tag and tag.get("content"):
            return {
                "kind": "img",
                "src": urljoin(base, tag["content"].strip()),
                "caption": "",
            }
    return None


def _collect_media(soup: BeautifulSoup, base: str, cap: int = 24) -> list[dict]:
    """Every usable media element on the page, in document order."""
    seen: set = set()
    out: list[dict] = []
    root = (
        soup.find("article")
        or soup.find("main")
        or soup.find(attrs={"role": "main"})
        or soup.body
        or soup
    )
    for scope in (root, soup):
        for el in scope.find_all(["figure", "img", "video", "iframe"]):
            item = _media_from(el, base, seen)
            if item:
                out.append(item)
            if len(out) >= cap:
                return out
        if out:
            break
    return out


def _decode(raw: bytes) -> str:
    """Bytes to text, guessing the encoding when the server lies or omits it."""
    for enc in ("utf-8",):
        try:
            return raw.decode(enc)
        except UnicodeDecodeError:
            pass
    try:
        import chardet

        guess = chardet.detect(raw[:16384]).get("encoding") or "latin-1"
    except Exception:
        guess = "latin-1"
    return raw.decode(guess, errors="replace")


def _td(value: Any, text: Optional[str] = None) -> str:
    """One table cell. Numeric-looking values get mono right-alignment.

    NOTE: the class string is built outside the f-string on purpose — a
    backslash inside an f-string expression is a SyntaxError on Python 3.11,
    which is what the Open WebUI image runs.
    """
    cls = ' class="num"' if _numeric(value) else ""
    return f"<td{cls}>{_e(value if text is None else text)}</td>"


def _v_pdf(raw: bytes, url: str, limit_pages: int = 8) -> tuple[str, int]:
    """Extract PDF text server-side. Returns (html, page_count)."""
    try:
        from pypdf import PdfReader
    except ImportError:
        return ('<p class="empty">pypdf is unavailable in this container.</p>', 0)
    try:
        reader = PdfReader(io.BytesIO(raw))
    except Exception as exc:
        return (
            f'<p class="empty">Could not parse this PDF ({_e(type(exc).__name__)}).</p>',
            0,
        )

    total = len(reader.pages)
    parts = []
    for i, page in enumerate(reader.pages[:limit_pages], 1):
        try:
            text = (page.extract_text() or "").strip()
        except Exception:
            text = ""
        if not text:
            continue
        paras = [p.strip() for p in re.split(r"\n\s*\n", text) if p.strip()]
        body = "".join(f"<p>{_e(_clip(p, 900))}</p>" for p in paras[:14])
        parts.append(f'<div class="pagemark">Page {i} of {total}</div>{body}')

    if not parts:
        return (
            '<p class="empty">No extractable text — this PDF is probably scanned '
            "images. Open the source to view it.</p>",
            total,
        )
    rest = total - min(total, limit_pages)
    more = (
        f'<p class="more">{rest} further pages in the source PDF.</p>'
        if rest > 0
        else ""
    )
    return (f'<div class="reader">{"".join(parts)}{more}</div>', total)


def _v_image(raw: bytes, ctype: str, url: str, inline_limit: int) -> str:
    """Inline the image as a data URI when small enough — no hotlink blocking
    or mixed-content surprises. Fall back to a direct <img src> when large."""
    dims = ""
    try:
        from PIL import Image

        with Image.open(io.BytesIO(raw)) as im:
            dims = f"{im.width} x {im.height} {im.format}"
    except Exception:
        pass
    kb = len(raw) / 1024
    meta = " · ".join(x for x in (dims, f"{kb:.0f} KB") if x)
    if len(raw) <= inline_limit:
        mime = (ctype or "image/png").split(";")[0].strip()
        src = f"data:{mime};base64,{base64.b64encode(raw).decode()}"
    else:
        src = url
    return (
        f'<div class="media"><img src="{_e(src)}" alt="" loading="lazy">'
        f'<span class="meta">{_e(meta)}</span></div>'
    )


