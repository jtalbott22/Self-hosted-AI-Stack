def _v_csv(text: str, limit: int) -> tuple[str, int, int]:
    """Render delimited text as a table. Returns (html, rows, cols)."""
    try:
        dialect = _csv.Sniffer().sniff(text[:8192], delimiters=",;\t|")
    except Exception:
        dialect = _csv.excel
    rows = [
        r for r in _csv.reader(io.StringIO(text), dialect) if any(c.strip() for c in r)
    ]
    if not rows:
        return ('<p class="empty">No rows found in this file.</p>', 0, 0)

    width = max(len(r) for r in rows)
    header_row = rows[0]
    has_header = any(c.strip() for c in header_row) and all(
        not _numeric(c) for c in header_row if c.strip()
    )
    headers = [_clip(c, 60) for c in header_row] if has_header else []
    data = rows[1:] if has_header else rows
    table = {
        "caption": "",
        "headers": headers,
        "rows": [[_clip(c, 120) for c in r] for r in data],
    }
    return (_v_tables([table], limit), len(data), width)


def _v_markdown(text: str) -> str:
    try:
        import markdown as _md

        html_body = _md.markdown(text, extensions=["tables", "fenced_code"])
    except Exception:
        return f'<pre class="raw">{_e(_clip(text, 6000))}</pre>'
    _, blocks = _extract_reader(_soup(html_body))
    return _v_reader(blocks, char_budget=3000)


def _v_plain(text: str, budget: int = 6000) -> str:
    text = text.strip()
    if not text:
        return '<p class="empty">Empty response.</p>'
    more = (
        f'<p class="more">{len(text) - budget:,} more characters in the source.</p>'
        if len(text) > budget
        else ""
    )
    return f'<pre class="raw">{_e(text[:budget])}</pre>{more}'


