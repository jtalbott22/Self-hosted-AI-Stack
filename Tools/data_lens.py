    # -- plumbing -----------------------------------------------------------

    _client: Optional[httpx.AsyncClient] = None
    _cache: dict = {}

    def _http(self) -> httpx.AsyncClient:
        """One pooled client for the process. Reusing connections skips the TCP
        and TLS handshake on every call after the first — typically 100-300 ms
        per request against an https host."""
        cls = type(self)
        if cls._client is None or cls._client.is_closed:
            cls._client = httpx.AsyncClient(
                timeout=self.valves.TIMEOUT,
                follow_redirects=True,
                max_redirects=4,
                headers={"User-Agent": UA},
                limits=httpx.Limits(
                    max_connections=32,
                    max_keepalive_connections=16,
                    keepalive_expiry=60.0,
                ),
            )
        return cls._client

    def _cache_get(self, key: str):
        ttl = self.valves.CACHE_SECONDS
        if ttl <= 0:
            return None
        hit = type(self)._cache.get(key)
        if hit and (time.time() - hit[0]) < ttl:
            return hit[1]
        return None

    def _cache_put(self, key: str, value) -> None:
        if self.valves.CACHE_SECONDS <= 0:
            return
        cache = type(self)._cache
        cache[key] = (time.time(), value)
        if len(cache) > 64:  # cheap bound; drop the oldest quarter
            for k in sorted(cache, key=lambda k: cache[k][0])[:16]:
                cache.pop(k, None)

    async def _get(self, url: str, accept: str = "*/*") -> tuple[bytes, str, str]:
        """Returns (raw_bytes, content_type, final_url). Cached by URL."""
        cached = self._cache_get(url)
        if cached is not None:
            return cached
        r = await self._http().get(url, headers={"Accept": accept})
        r.raise_for_status()
        if len(r.content) > self.valves.MAX_BYTES:
            raise ValueError("Response exceeded MAX_BYTES.")
        out = (r.content, r.headers.get("content-type", ""), str(r.url))
        self._cache_put(url, out)
        return out

    async def _searx(
        self, query: str, time_range: str = "", category: str = ""
    ) -> list[dict]:
        url = f"{self.valves.SEARXNG_URL}?q={quote_plus(query)}&format=json"
        if time_range in ("day", "week", "month", "year"):
            url += f"&time_range={time_range}"
        if category in ("images", "videos", "news", "science", "it", "music"):
            url += f"&categories={category}"
        raw, _, _ = await self._get(url, accept="application/json")
        return json.loads(raw).get("results", []) or []

    async def _render_js(self, url: str) -> str:
        """Playwright fallback for JS-built pages.

        Tries the configured endpoint two ways — connect() for a Playwright
        run-server/launch-server, connect_over_cdp() for browserless or a raw
        Chrome DevTools endpoint — then a browser local to this container.
        Every failure is reported verbatim, because "renderer unavailable" with
        no detail is useless for fixing the endpoint.
        """
        from playwright.async_api import async_playwright

        endpoint = (self.valves.PLAYWRIGHT_WS or "").strip()
        tried: list[str] = []
        async with async_playwright() as p:
            browser = None
            if endpoint:
                attempts = [("connect", p.chromium.connect)]
                if endpoint.startswith(("http://", "https://", "ws://", "wss://")):
                    attempts.append(("connect_over_cdp", p.chromium.connect_over_cdp))
                for label, fn in attempts:
                    try:
                        browser = await fn(endpoint, timeout=8000)
                        break
                    except Exception as exc:
                        first = str(exc).strip().splitlines()[0][:150]
                        tried.append(f"{label} -> {type(exc).__name__}: {first}")
            else:
                tried.append("PLAYWRIGHT_WS is empty")
            if browser is None:
                try:
                    browser = await p.chromium.launch(headless=True)
                except Exception as exc:
                    first = str(exc).strip().splitlines()[0][:150]
                    tried.append(f"local launch -> {type(exc).__name__}: {first}")
                    raise RuntimeError("; ".join(tried))
            try:
                page = await browser.new_page(user_agent=UA)
                await page.goto(url, timeout=12000, wait_until="domcontentloaded")
                await asyncio.sleep(1.2)  # let late XHRs paint
                return await page.content()
            finally:
                await browser.close()

