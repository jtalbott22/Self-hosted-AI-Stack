    async def _inline_media(self, items: list[dict]) -> dict:
        """Fetch the first few images concurrently and turn them into data URIs.

        Linking usually works, but hotlink protection and referrer checks kill
        it often enough to be annoying. Inlining the lead images makes them
        certain; the rest stay as plain URLs so this stays fast.
        """
        n = self.valves.INLINE_PAGE_IMAGES
        if n <= 0:
            return {}
        targets = [it["src"] for it in items if it["kind"] == "img"][:n]
        if not targets:
            return {}
        cap = self.valves.INLINE_IMAGE_KB * 1024

        async def one(u: str):
            try:
                raw, ct, _ = await self._get(u, accept="image/*")
                if ct.split(";")[0].strip().startswith("image/") and len(raw) <= cap:
                    b64 = base64.b64encode(raw).decode()
                    return u, f"data:{ct.split(';')[0].strip()};base64,{b64}"
            except Exception:
                pass
            return u, None

        results = await asyncio.gather(
            *(one(u) for u in targets), return_exceptions=True
        )
        return {u: v for r in results if isinstance(r, tuple) for u, v in [r] if v}

    async def search_web(
        self,
        query: str,
        time_range: str = "",
        category: str = "",
        __event_emitter__=None,
    ) -> tuple:
        """
        Searches the web and instantly shows a results panel to the user. The panel
        is already visible when you receive this result — reply with ONE short
        sentence at most, and never re-list the results yourself. Each result has an
        Open button the user can click to view that page's data.

        The search index is always live and current. Your training data is not.
        NEVER put a year in the query unless the user explicitly named one — write
        "macbook pro price" and not "macbook pro price 2024". Use time_range to ask
        for recent material instead.

        :param query: Concise web search terms. No year unless the user named one.
        :param time_range: Optional recency filter: "day", "week", "month", or "year". Set this for questions about current prices, latest releases, or breaking news. Leave empty for general or historical questions.
        :param category: Optional result type. Use "images" when the user wants to see pictures, photos, diagrams, or what something looks like; "videos" whenever the user asks to watch, see, or find a video, clip, interview, or footage; "news" for current events. Images render as a carousel and videos as playable thumbnails that embed a real player in the chat when clicked.
        """
        t0 = time.perf_counter()
        note = ""
        if self.valves.STRIP_STALE_YEARS:
            query, note = _freshen(query)
        if __event_emitter__:
            await __event_emitter__(
                {
                    "type": "status",
                    "data": {
                        "description": f"Searching “{_clip(query, 60)}”…",
                        "done": False,
                    },
                }
            )
        try:
            hits = await self._searx(query, time_range, category)
        except Exception as exc:
            if __event_emitter__:
                await __event_emitter__(
                    {
                        "type": "status",
                        "data": {"description": "Search failed", "done": True},
                    }
                )
            return (
                _fault_panel(
                    "Search failed.",
                    f"<code>{_e(type(exc).__name__)}</code>: {_e(str(exc)[:180])}<br>"
                    "Check the SEARXNG_URL valve, and confirm searxng's "
                    "<code>settings.yml</code> has <code>search: formats: [html, json]</code> "
                    "— without json the API returns 403.",
                    self.valves.THEME,
                ),
                {
                    "status": "error",
                    "reason": "search_failed",
                    "detail": str(exc)[:200],
                },
            )

        limit = self.valves.RESULT_LIMIT
        if category in ("images", "videos"):
            limit = max(limit, 18)
        shown = min(len(hits), limit)
        ms = (time.perf_counter() - t0) * 1000

        if category == "images":
            body = _v_result_carousel(hits, limit)
        elif category == "videos":
            body = _v_video_grid(hits, limit)
        else:
            body = _v_results(hits, limit)

        # A carousel is already a single-item view; a filter bar over it would
        # fight the strip. Everything else gets slice-and-dice.
        toolbar = "" if category == "images" else _filter_bar(hits, shown)

        sub = f"{shown} of {len(hits)} results"
        if category:
            sub += f" · {category}"
        if time_range:
            sub += f" · past {time_range}"
        if note:
            sub += f" · {note}"
        html_out = _shell(
            f"Search · {_clip(query, 60)}",
            sub,
            f"{time.strftime('%H:%M:%S')} · {ms:.0f}MS",
            body,
            [
                (
                    "More results",
                    f"Search the web again for: {query} (show more results)",
                )
            ],
            toolbar=toolbar,
            theme=self.valves.THEME,
        )
        if __event_emitter__:
            await __event_emitter__(
                {
                    "type": "status",
                    "data": {
                        "description": f"{len(hits)} results in {ms:.0f} ms",
                        "done": True,
                        "hidden": True,
                    },
                }
            )
        return (
            HTMLResponse(content=html_out, headers={"Content-Disposition": "inline"}),
            {
                "status": "success",
                "query": query,
                "results_shown": min(len(hits), limit),
                "today": time.strftime("%Y-%m-%d"),
                "query_adjusted": note or None,
                "time_range": time_range or None,
                "category": category or None,
                "top_results": [
                    {"title": _clip(h.get("title", ""), 70), "url": h.get("url", "")}
                    for h in hits[:5]
                ],
                "note": "Results panel is already on screen. Reply in one short sentence; "
                "do not list the results. Today's date is given above — trust it "
                "over your training data for anything time-sensitive.",
            },
        )

    async def chart_data(
        self,
        url: str,
        chart: str = "auto",
        label_column: str = "",
        value_columns: Optional[list[str]] = None,
        table_index: int = 0,
        limit: int = 14,
        title: str = "",
        __event_emitter__=None,
    ) -> tuple:
        """
        Charts tabular data from any URL and shows it instantly as a panel.

        CALL THIS whenever the user asks to chart, graph, plot, or visualize data,
        or asks for a pie chart, line chart, bar chart, breakdown, trend, or
        comparison. Works on CSV and TSV files, JSON APIs, and any HTML page's
        tables. If the user is looking at a table you just rendered, pass that same
        URL — the response is cached, so the chart is effectively free.

        Do not describe the numbers afterwards; the chart is already visible. Reply
        in ONE short sentence.

        :param url: The full http(s) URL of the CSV, JSON, or page holding the table.
        :param chart: "pie", "bar", or "line". Use "auto" to let the server pick from the data shape. Prefer "pie" for parts of a whole, "line" for values over time, "bar" for comparing categories.
        :param label_column: Name of the column holding the category or date labels. Leave empty to auto-detect.
        :param value_columns: Names of the numeric columns to plot. Leave empty to auto-detect. Pie charts use only the first.
        :param table_index: Which table on the page, 0 for the largest. Only used for HTML pages with several tables.
        :param limit: Maximum categories or points to plot. Default 14.
        :param title: Short panel heading in the user's own words. Optional.
        """
        t0 = time.perf_counter()
        url = url.strip()
        if url and not urlparse(url).scheme:
            url = "https://" + url

        block = _url_block_reason(url, self.valves.ALLOW_PRIVATE_NETWORKS)
        if block:
            return (
                _fault_panel("Can't open that address.", _e(block), self.valves.THEME),
                {"status": "error", "reason": "blocked_url", "detail": block},
            )

        if __event_emitter__:
            await __event_emitter__(
                {
                    "type": "status",
                    "data": {"description": f"Charting {_host(url)}…", "done": False},
                }
            )

        try:
            raw, ctype, url = await self._get(
                url, accept="text/csv,application/json,text/html;q=0.9,*/*;q=0.8"
            )
        except Exception as exc:
            return (
                _fault_panel(
                    f"Could not read {_host(url) or url}.",
                    f"<code>{_e(type(exc).__name__)}</code>: " f"{_e(str(exc)[:180])}",
                    self.valves.THEME,
                ),
                {
                    "status": "error",
                    "reason": "fetch_failed",
                    "url": url,
                    "detail": str(exc)[:200],
                },
            )

        # ---- get rows out of whatever this is ------------------------------
        ct = (ctype or "").split(";")[0].strip().lower()
        path = urlparse(url).path.lower()
        rows: list[dict] = []
        source = _host(url)

        if ct in (
            "text/csv",
            "text/tab-separated-values",
            "application/csv",
        ) or path.endswith((".csv", ".tsv")):
            rows, source = _csv_rows(_decode(raw)), f"{_host(url)} · data file"
        elif "json" in ct:
            try:
                rows = _json_rows(json.loads(_decode(raw)))
            except json.JSONDecodeError:
                rows = []
            source = f"{_host(url)} · JSON"
        else:
            soup = _soup(_decode(raw))
            tables = _extract_tables(soup, url)
            if tables:
                idx = min(max(table_index, 0), len(tables) - 1)
                rows = _table_to_rows(tables[idx])
                cap = tables[idx].get("caption") or ""
                source = cap or (
                    soup.title.get_text(strip=True)[:80] if soup.title else _host(url)
                )

        if not rows:
            return (
                _fault_panel(
                    f"No tabular data found at {_host(url)}.",
                    "Charts need rows and columns — a CSV, a JSON array, or an "
                    "HTML table. Open the page first to see what is there.",
                    self.valves.THEME,
                ),
                {"status": "error", "reason": "no_rows", "url": url},
            )

        chart = (chart or "auto").strip().lower()
        if chart not in ("auto", "pie", "bar", "line"):
            chart = "auto"
        body, meta = _build_chart(rows, chart, label_column, value_columns, limit)

        ms = (time.perf_counter() - t0) * 1000
        picked = meta.get("value_columns") or []
        sub = source
        if picked:
            sub += f" · {meta.get('label_column')} vs {', '.join(picked)}"

        chips = [("Table", f"Open {url} and show the table.")]
        for alt in ("bar", "line", "pie"):
            if alt != meta.get("chart"):
                chips.append((alt.title(), f"Chart {url} as a {alt} chart."))

        html_out = _shell(
            title or f"Chart · {_clip(source, 50)}",
            sub,
            f"{time.strftime('%H:%M:%S')} · {ms:.0f}MS",
            body,
            chips[:4],
            theme=self.valves.THEME,
        )
        if __event_emitter__:
            await __event_emitter__(
                {
                    "type": "status",
                    "data": {
                        "description": f"Charted in {ms:.0f} ms",
                        "done": True,
                        "hidden": True,
                    },
                }
            )
        return (
            HTMLResponse(content=html_out, headers={"Content-Disposition": "inline"}),
            {
                "status": "success",
                "url": url,
                "rows_available": len(rows),
                "render_ms": round(ms),
                **meta,
                "note": "The chart is already on screen. Reply in one short sentence; "
                "do not list or restate the values.",
            },
        )

    async def open_page(
        self,
        url: str,
        view: str = "auto",
        render_js: bool = False,
        limit: int = 30,
        __event_emitter__=None,
    ) -> tuple:
        """
        Fetches any browsable webpage, document, data file, image, or video and
        instantly shows it to the user as a panel. Handles HTML pages, JSON APIs,
        PDFs, CSV/TSV files, Markdown, images, video files, and YouTube/Vimeo links
        — it picks the right renderer from the content type automatically. The panel
        is already visible when you receive this result — reply with ONE short
        sentence at most, and NEVER restate, summarize, or re-type the content.

        :param url: The full http(s) URL to open.
        :param view: Leave as "auto" almost always — it detects the content type and picks the best renderer. Override with "media" when the user wants to see the page's images, photos, figures, or video; "table" to force table extraction; "text" to force readable page text.
        :param render_js: Set true only if a previous attempt on this URL found no content, meaning the page builds itself with JavaScript.
        :param limit: Maximum table or data rows to display. Default 30.
        """
        t0 = time.perf_counter()
        url = url.strip()
        if url and not urlparse(url).scheme:
            url = "https://" + url

        block = _url_block_reason(url, self.valves.ALLOW_PRIVATE_NETWORKS)
        if block:
            return (
                _fault_panel("Can't open that address.", _e(block), self.valves.THEME),
                {"status": "error", "reason": "blocked_url", "detail": block},
            )

        if __event_emitter__:
            await __event_emitter__(
                {
                    "type": "status",
                    "data": {"description": f"Opening {_host(url)}…", "done": False},
                }
            )

        # ---- oEmbed shortcut: no fetch needed ------------------------------
        embed = _embed_url(url)
        if embed and view in ("auto", "embed"):
            return (
                HTMLResponse(
                    content=_shell(
                        _host(url),
                        url,
                        time.strftime("%H:%M:%S"),
                        _v_embed(embed),
                        [("Read page", f"Open {url} and show the page text.")],
                        theme=self.valves.THEME,
                    ),
                    headers={"Content-Disposition": "inline"},
                ),
                {
                    "status": "success",
                    "url": url,
                    "mode": "embed",
                    "note": "A video player is on screen. Its contents are not "
                    "available to you; do not describe them.",
                },
            )

        # ---- fetch ---------------------------------------------------------
        raw, ctype, err = b"", "", None
        html_text, payload_json, js_note = "", None, ""
        if render_js:
            try:
                html_text, ctype = await self._render_js(url), "text/html"
            except Exception as exc:
                # Never dead-end on a renderer problem — fall through to the
                # plain fetch and tell the user what happened.
                js_note = f"JS render failed — {exc}"
                render_js = False
        if not html_text:
            try:
                raw, ctype, url = await self._get(
                    url, accept="text/html,application/json;q=0.9,*/*;q=0.8"
                )
            except Exception as exc:
                err = exc

        if err is not None:
            if __event_emitter__:
                await __event_emitter__(
                    {
                        "type": "status",
                        "data": {"description": "Fetch failed", "done": True},
                    }
                )
            status = getattr(getattr(err, "response", None), "status_code", None)
            if status in (401, 403, 405, 429):
                how = (
                    f"The site returned HTTP {status} — it refuses automated "
                    "clients. JavaScript rendering will not help; a browser "
                    "endpoint that presents real browser headers might."
                )
            elif status:
                how = f"The site returned HTTP {status}."
            else:
                how = f"<code>{_e(type(err).__name__)}</code>: {_e(str(err)[:180])}"
            if js_note:
                how += f"<br>{_e(js_note)} — the plain fetch was tried instead."
            return (
                _fault_panel(
                    f"Could not open {_host(url) or url}.", how, self.valves.THEME
                ),
                {
                    "status": "error",
                    "reason": "fetch_failed",
                    "url": url,
                    "http_status": status,
                    "js_renderer": js_note or None,
                    "detail": str(err)[:200],
                },
            )

        # ---- route by content type ----------------------------------------
        title, subtitle, body = _host(url), url, ""
        mode, table_count, block_count = "", 0, 0
        extra: dict = {}
        ct = (ctype or "").split(";")[0].strip().lower()
        path = urlparse(url).path.lower()

        if ct == "application/pdf" or path.endswith(".pdf"):
            mode = "pdf"
            body, pages = _v_pdf(raw, url)
            extra["pages"] = pages
            title = f"{_host(url)} · PDF"

        elif ct.startswith("image/"):
            mode = "image"
            body = _v_image(raw, ct, url, self.valves.INLINE_IMAGE_KB * 1024)
            title = f"{_host(url)} · image"

        elif ct.startswith("video/"):
            mode = "video"
            body = _v_video(url, ct)
            title = f"{_host(url)} · video"

        elif ct in (
            "text/csv",
            "text/tab-separated-values",
            "application/csv",
        ) or path.endswith((".csv", ".tsv")):
            mode = "csv"
            body, nrows, ncols = _v_csv(_decode(raw), limit)
            extra.update(rows=nrows, columns=ncols)
            title = f"{_host(url)} · data file"

        elif "json" in ct and view in ("auto", "json"):
            mode = "json"
            try:
                payload_json = json.loads(_decode(raw))
                body = _v_json(payload_json, limit)
            except json.JSONDecodeError:
                mode, body = "text", _v_plain(_decode(raw))
            title = f"{_host(url)} · JSON"

        elif ct in ("text/markdown", "text/x-markdown") or path.endswith(
            (".md", ".markdown")
        ):
            mode = "text"
            body = _v_markdown(_decode(raw))
            title = f"{_host(url)} · markdown"

        elif ct == "text/plain" and not path.endswith((".html", ".htm")):
            mode = "text"
            body = _v_plain(_decode(raw))

        else:
            html_text = html_text or _decode(raw)
            soup = _soup(html_text)
            tables = _extract_tables(soup, url)
            page_title, blocks = _extract_reader(soup, base=url, with_media=True)
            title = page_title or _host(url)
            table_count, block_count = len(tables), len(blocks)
            media_items = [v for k, v in blocks if k == "media"]

            if view == "media":
                mode = "media"
                gallery = _collect_media(soup, url) or media_items
                if not gallery:
                    hero = _hero_image(soup, url)
                    gallery = [hero] if hero else []
                inlined = await self._inline_media(gallery)
                body = _v_gallery(gallery, inlined)
                extra["media_found"] = len(gallery)
            elif view == "table" or (view == "auto" and tables):
                mode = "table"
                body = (
                    _v_tables(tables, limit)
                    if tables
                    else ('<p class="empty">No data tables found on this page.</p>')
                )
            else:
                mode = "text"
                if not media_items:
                    hero = _hero_image(soup, url)
                    if hero:
                        blocks = [("media", hero)] + blocks
                        media_items = [hero]
                inlined = await self._inline_media(media_items)
                body = _v_reader(blocks, char_budget=2400, inlined=inlined)
            extra["media_found"] = extra.get("media_found", len(media_items))

        ms = (time.perf_counter() - t0) * 1000
        if js_note:
            subtitle = f"{url} · {_clip(js_note, 110)} · showed plain fetch"
        chips = [("Refresh", f"Open {url} and show me the data again.")]
        if mode in ("table", "csv", "json"):
            chips.append(("Chart it", f"Chart the data from {url}."))
            chips.append(("Pie", f"Chart {url} as a pie chart."))
        if mode != "table" and table_count:
            chips.append(("Tables", f"Open {url} and show the tables."))
        if mode != "text" and block_count:
            chips.append(("Read page", f"Open {url} and show the page text."))
        if mode != "media" and extra.get("media_found"):
            chips.append(("Show media", f"Open {url} and show the images and video."))
        if mode == "text" and block_count == 0 and not render_js:
            chips.append(("Render JS", f"Open {url} with JavaScript rendering."))
        chips.append(("Source ↗", ""))  # replaced below with a plain link

        # dock: last chip is actually an anchor, swap it in
        html_out = _shell(
            title,
            subtitle,
            f"{time.strftime('%H:%M:%S')} · {ms:.0f}MS",
            body,
            chips[:-1],
            theme=self.valves.THEME,
        )
        html_out = html_out.replace(
            '<div class="dock">',
            f'<div class="dock"><a href="{_e(url)}" data-external target="_blank" '
            f'rel="noopener noreferrer" style="font-size:11px">Source ↗</a>'
            f'<button data-copy="{_e(url)}">Copy link</button>',
            1,
        )

        if __event_emitter__:
            await __event_emitter__(
                {
                    "type": "status",
                    "data": {
                        "description": f"Rendered {mode} in {ms:.0f} ms",
                        "done": True,
                        "hidden": True,
                    },
                }
            )
        return (
            HTMLResponse(content=html_out, headers={"Content-Disposition": "inline"}),
            {
                "status": "success",
                "url": url,
                "title": _clip(title, 90),
                "mode": mode,
                "tables_found": table_count,
                "text_blocks_found": block_count,
                "render_ms": round(ms),
                **extra,
                "js_rendered": bool(render_js),
                "js_renderer_error": js_note or None,
                "note": "The page's data is already on screen verbatim. Reply in one "
                "short sentence; do not restate or summarize the content. "
                "If js_rendered is false, JavaScript rendering did NOT run — "
                "never tell the user it did.",
            },
        )
