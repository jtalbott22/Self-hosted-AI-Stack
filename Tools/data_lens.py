def _min_css(text: str) -> str:
    """Strip comments and collapse whitespace. Safe: the stylesheet has no
    content strings that depend on spacing."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"\s+", " ", text)
    text = re.sub(r"\s*([{}:;,>])\s*", r"\1", text)
    return text.replace(";}", "}").strip()


def _min_js(text: str) -> str:
    """Strip block comments and leading indentation only. Newlines are kept so
    automatic semicolon insertion behaves exactly as written."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    lines = [ln.strip() for ln in text.splitlines()]
    return "\n".join(ln for ln in lines if ln)


