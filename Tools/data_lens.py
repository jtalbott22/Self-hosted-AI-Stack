def _soup(html_text: str) -> BeautifulSoup:
    # lxml ships with Open WebUI and parses 2-5x faster than html.parser.
    try:
        soup = BeautifulSoup(html_text, "lxml")
    except Exception:
        soup = BeautifulSoup(html_text, "html.parser")
    for tag in soup.find_all(_STRIP_TAGS):
        tag.decompose()
    return soup


def _extract_tables(soup: BeautifulSoup, base_url: str) -> list[dict]:
    """Return scored tables: {caption, headers, rows}."""
    out = []
    for t in soup.find_all("table"):
        headers: list[str] = []
        thead = t.find("thead")
        header_row = (thead.find("tr") if thead else None) or t.find("tr")
        if header_row:
            cells = header_row.find_all(["th", "td"])
            if cells and header_row.find("th"):
                headers = [_clip(c.get_text(" ", strip=True), 60) for c in cells]

        rows = []
        for tr in t.find_all("tr"):
            if tr is header_row and headers:
                continue
            cells = tr.find_all(["td", "th"])
            if not cells:
                continue
            rows.append([_clip(c.get_text(" ", strip=True), 120) for c in cells])
        rows = [r for r in rows if any(x for x in r)]
        if not rows:
            continue
        width = max(len(r) for r in rows)
        if width < 2 or len(rows) < 2:
            continue

        cap = ""
        cap_el = t.find("caption")
        if cap_el:
            cap = _clip(cap_el.get_text(" ", strip=True), 90)
        if not cap:
            prev = t.find_previous(["h1", "h2", "h3", "h4"])
            if prev:
                cap = _clip(prev.get_text(" ", strip=True), 90)

        out.append(
            {
                "caption": cap,
                "headers": headers,
                "rows": rows,
                "score": len(rows) * width,
            }
        )
    out.sort(key=lambda x: x["score"], reverse=True)
    return out


def _extract_reader(
    soup: BeautifulSoup, base: str = "", with_media: bool = False
) -> tuple[str, list[tuple[str, Any]]]:
    """Return (page_title, [(kind, value)]) where kind is p/h2/li or media.

    Media blocks come back in document order, so a figure renders beside the
    paragraph it illustrates rather than in a pile at the bottom.
    """
    title = ""
    if soup.title:
        title = _clip(soup.title.get_text(strip=True), 110)
    h1 = soup.find("h1")
    if h1:
        title = _clip(h1.get_text(" ", strip=True), 110) or title

    root = (
        soup.find("article")
        or soup.find("main")
        or soup.find(attrs={"role": "main"})
        or soup.body
        or soup
    )

    wanted = ["p", "h2", "h3", "li"]
    if with_media:
        wanted += ["figure", "img", "video", "iframe"]

    seen: set = set()
    inside_figure: set = set()
    if with_media:
        for fig in root.find_all("figure"):
            for inner in fig.find_all(["img", "video"]):
                inside_figure.add(id(inner))

    blocks: list[tuple[str, Any]] = []
    for el in root.find_all(wanted):
        if el.name in ("figure", "img", "video", "iframe"):
            if id(el) in inside_figure:
                continue  # already emitted via its <figure>
            item = _media_from(el, base, seen)
            if item:
                blocks.append(("media", item))
            continue
        txt = el.get_text(" ", strip=True)
        if not txt or len(txt) < 25 and el.name == "p":
            continue
        kind = "h2" if el.name in ("h2", "h3") else ("li" if el.name == "li" else "p")
        blocks.append((kind, txt))

    if any(k != "media" for k, _ in blocks):
        return title, blocks

    # Div-soup fallback: plenty of real pages (and most JS frameworks' output)
    # wrap every paragraph in an unsemantic <div>. Take leaf-ish containers
    # whose own text is substantial, so we don't grab a whole page wrapper.
    text_blocks: list[tuple[str, Any]] = []
    for el in root.find_all(["div", "section", "span", "td"]):
        if el.find(["div", "section", "p", "li"]):
            continue
        txt = el.get_text(" ", strip=True)
        if len(txt) >= 40:
            text_blocks.append(("p", txt))
    if text_blocks:
        return title, blocks + text_blocks

    # Last resort: the document's own text, split on blank lines.
    whole = root.get_text("\n", strip=True)
    text_blocks = [
        ("p", chunk.strip())
        for chunk in re.split(r"\n{2,}", whole)
        if len(chunk.strip()) >= 40
    ]
    return title, blocks + text_blocks


