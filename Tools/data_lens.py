_DATEISH = re.compile(
    r"^\s*(\d{4}([-/]\d{1,2})?([-/]\d{1,2})?|"
    r"(jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*\.?\s*\d{0,4}|"
    r"q[1-4](\s*\d{4})?|\d{1,2}[-/]\d{1,2}([-/]\d{2,4})?)\s*$",
    re.I,
)


def _num(v: Any) -> Optional[float]:
    """Parse a number out of a cell, tolerating $ , % and stray units."""
    if isinstance(v, bool):
        return None
    if isinstance(v, (int, float)):
        return float(v)
    if v is None:
        return None
    s = str(v).strip()
    if not s:
        return None
    neg = s.startswith("(") and s.endswith(")")  # (1,234) accounting negative
    s = re.sub(r"[^\d.eE+-]", "", s.replace(",", ""))
    if s in ("", "-", "+", ".", "e", "E"):
        return None
    try:
        n = float(s)
    except ValueError:
        return None
    return -n if neg else n


def _fmt_num(n: float) -> str:
    a = abs(n)
    if a >= 1_000_000_000:
        return f"{n / 1_000_000_000:.1f}B"
    if a >= 1_000_000:
        return f"{n / 1_000_000:.1f}M"
    if a >= 10_000:
        return f"{n / 1_000:.1f}K"
    if n == int(n):
        return f"{int(n):,}"
    return f"{n:,.2f}".rstrip("0").rstrip(".")


def _csv_rows(text: str) -> list[dict]:
    try:
        dialect = _csv.Sniffer().sniff(text[:8192], delimiters=",;\t|")
    except Exception:
        dialect = _csv.excel
    raw = (
        [r for r in _csv.reader(io.StringIO(text)) if any(c.strip() for c in r)]
        if dialect is _csv.excel
        else [
            r
            for r in _csv.reader(io.StringIO(text), dialect)
            if any(c.strip() for c in r)
        ]
    )
    if len(raw) < 2:
        return []
    head = [c.strip() or f"col{i + 1}" for i, c in enumerate(raw[0])]
    return [dict(zip(head, r)) for r in raw[1:]]


def _json_rows(payload: Any) -> list[dict]:
    if isinstance(payload, list):
        return [r for r in payload if isinstance(r, dict)]
    if isinstance(payload, dict):
        for key in ("rows", "data", "items", "results", "records", "series"):
            v = payload.get(key)
            if isinstance(v, list) and v and isinstance(v[0], dict):
                return v
        flat = {k: v for k, v in payload.items() if not isinstance(v, (dict, list))}
        if flat:  # a flat object charts as one row of key/value pairs
            return [{"name": k, "value": v} for k, v in flat.items()]
    return []


def _table_to_rows(t: dict) -> list[dict]:
    headers = t.get("headers") or []
    rows = t.get("rows") or []
    if not rows:
        return []
    width = max(len(r) for r in rows)
    if not headers:
        headers = [f"col{i + 1}" for i in range(width)]
    headers = (headers + [f"col{i + 1}" for i in range(len(headers), width)])[:width]
    return [dict(zip(headers, r)) for r in rows]


def _columns_of(rows: list[dict]) -> list[str]:
    seen: list[str] = []
    for r in rows[:50]:
        for k in r:
            if k not in seen:
                seen.append(k)
    return seen


def _numeric_columns(rows: list[dict]) -> list[str]:
    out = []
    for c in _columns_of(rows):
        vals = [_num(r.get(c)) for r in rows[:30]]
        hits = [v for v in vals if v is not None]
        if hits and len(hits) >= max(2, int(len(vals) * 0.6)):
            out.append(c)
    return out


def _pick_label_column(rows: list[dict], numeric: list[str]) -> Optional[str]:
    for c in _columns_of(rows):
        if c not in numeric:
            return c
    return _columns_of(rows)[0] if rows else None


def _looks_temporal(labels: list[str]) -> bool:
    if len(labels) < 3:
        return False
    hits = sum(1 for l in labels if _DATEISH.match(str(l)))
    return hits >= len(labels) * 0.6


def _chart_series(rows, label_col, value_cols, limit):
    labels, series = [], {c: [] for c in value_cols}
    for r in rows[:limit]:
        labels.append(_clip(str(r.get(label_col, "")), 28))
        for c in value_cols:
            series[c].append(_num(r.get(c)) or 0.0)
    return labels, series


def _legend(names: list[str]) -> str:
    items = "".join(
        f'<span class="lg"><i style="background:{CHART_PALETTE[i % len(CHART_PALETTE)]}">'
        f"</i>{_e(n)}</span>"
        for i, n in enumerate(names)
    )
    return f'<div class="legend">{items}</div>'


def _svg_bar(labels, series, horizontal=False) -> str:
    names = list(series)
    vals = [v for c in names for v in series[c]]
    hi = max(vals + [0.0])
    lo = min(vals + [0.0])
    span = (hi - lo) or 1.0
    n, g = len(labels), len(names)

    if horizontal or (n > 10 and g == 1):
        W, rowh = 760, 26
        PAD_L, PAD_R = 150, 46
        H = 14 + n * rowh
        iw = W - PAD_L - PAD_R
        bars = []
        for i, lab in enumerate(labels):
            y = 7 + i * rowh
            v = series[names[0]][i]
            w = max((v - min(lo, 0)) / span * iw, 1)
            bars.append(
                f'<text class="axis" x="{PAD_L - 8}" y="{y + rowh / 2 + 3:.0f}" '
                f'text-anchor="end">{_e(_clip(lab, 24))}</text>'
                f'<rect x="{PAD_L}" y="{y + 3}" width="{w:.1f}" height="{rowh - 10}" '
                f'fill="{CHART_PALETTE[0]}" rx="1"/>'
                f'<text class="val" x="{PAD_L + w + 6:.1f}" y="{y + rowh / 2 + 3:.0f}">'
                f"{_e(_fmt_num(v))}</text>"
            )
        return (
            f'<svg class="chart" viewBox="0 0 {W} {H}" role="img" '
            f'aria-label="Bar chart, {n} categories">{"".join(bars)}</svg>'
        )

    W, H = 760, 320
    PAD_L, PAD_B, PAD_T, PAD_R = 52, 46, 14, 10
    iw, ih = W - PAD_L - PAD_R, H - PAD_B - PAD_T
    slot = iw / max(n, 1)
    bw = min(slot / (g + 0.6), 54)

    def y_of(v):
        return PAD_T + ih - ((v - min(lo, 0)) / span) * ih

    grid, ticks = [], []
    for f in (0, 0.25, 0.5, 0.75, 1):
        yy = PAD_T + ih * f
        grid.append(
            f'<line x1="{PAD_L}" y1="{yy:.1f}" x2="{PAD_L + iw}" '
            f'y2="{yy:.1f}" stroke="var(--rule)" stroke-width="1"/>'
        )
        ticks.append(
            f'<text class="axis" x="{PAD_L - 7}" y="{yy + 3:.1f}" '
            f'text-anchor="end">{_e(_fmt_num(hi - span * f))}</text>'
        )

    bars, xlab = [], []
    rotate = n > 6 or any(len(l) > 8 for l in labels)
    for i, lab in enumerate(labels):
        cx = PAD_L + slot * i + slot / 2
        for j, name in enumerate(names):
            v = series[name][i]
            x = cx - (g * bw) / 2 + j * bw
            top, base = y_of(v), y_of(min(lo, 0))
            y0, hh = min(top, base), abs(base - top)
            bars.append(
                f'<rect x="{x:.1f}" y="{y0:.1f}" width="{bw - 3:.1f}" '
                f'height="{max(hh, 1):.1f}" rx="1" '
                f'fill="{CHART_PALETTE[j % len(CHART_PALETTE)]}"><title>'
                f"{_e(lab)} · {_e(name)}: {_e(_fmt_num(v))}</title></rect>"
            )
        if rotate:
            xlab.append(
                f'<text class="axis" x="{cx:.1f}" y="{PAD_T + ih + 12:.0f}" '
                f'text-anchor="end" transform="rotate(-38 {cx:.1f} '
                f'{PAD_T + ih + 12:.0f})">{_e(_clip(lab, 18))}</text>'
            )
        else:
            xlab.append(
                f'<text class="axis" x="{cx:.1f}" y="{PAD_T + ih + 15:.0f}" '
                f'text-anchor="middle">{_e(_clip(lab, 14))}</text>'
            )

    return (
        f'<svg class="chart" viewBox="0 0 {W} {H}" role="img" '
        f'aria-label="Bar chart, {n} categories">'
        f'{"".join(grid)}{"".join(bars)}{"".join(ticks)}{"".join(xlab)}</svg>'
    )


def _svg_line(labels, series) -> str:
    names = list(series)
    vals = [v for c in names for v in series[c]]
    hi, lo = max(vals + [0.0]), min(vals + [0.0])
    span = (hi - lo) or 1.0
    n = len(labels)
    W, H = 760, 320
    PAD_L, PAD_B, PAD_T, PAD_R = 52, 40, 14, 12
    iw, ih = W - PAD_L - PAD_R, H - PAD_B - PAD_T

    def x_of(i):
        return PAD_L + (i / max(n - 1, 1)) * iw

    def y_of(v):
        return PAD_T + ih - ((v - lo) / span) * ih

    grid, ticks = [], []
    for f in (0, 0.5, 1):
        yy = PAD_T + ih * f
        grid.append(
            f'<line x1="{PAD_L}" y1="{yy:.1f}" x2="{PAD_L + iw}" '
            f'y2="{yy:.1f}" stroke="var(--rule)" stroke-width="1"/>'
        )
        ticks.append(
            f'<text class="axis" x="{PAD_L - 7}" y="{yy + 3:.1f}" '
            f'text-anchor="end">{_e(_fmt_num(hi - span * f))}</text>'
        )

    paths = []
    for j, name in enumerate(names):
        colour = CHART_PALETTE[j % len(CHART_PALETTE)]
        pts = " ".join(
            f"{x_of(i):.1f},{y_of(v):.1f}" for i, v in enumerate(series[name])
        )
        paths.append(
            f'<polyline points="{pts}" fill="none" stroke="{colour}" '
            f'stroke-width="2" stroke-linejoin="round" '
            f'stroke-linecap="round"/>'
        )
        if n <= 40:
            for i, v in enumerate(series[name]):
                paths.append(
                    f'<circle cx="{x_of(i):.1f}" cy="{y_of(v):.1f}" r="2.5" '
                    f'fill="{colour}"><title>{_e(labels[i])} · {_e(name)}: '
                    f"{_e(_fmt_num(v))}</title></circle>"
                )

    step = max(1, n // 8)
    xlab = "".join(
        f'<text class="axis" x="{x_of(i):.1f}" y="{PAD_T + ih + 16:.0f}" '
        f'text-anchor="middle">{_e(_clip(labels[i], 12))}</text>'
        for i in range(0, n, step)
    )
    return (
        f'<svg class="chart" viewBox="0 0 {W} {H}" role="img" '
        f'aria-label="Line chart, {n} points">'
        f'{"".join(grid)}{"".join(paths)}{"".join(ticks)}{xlab}</svg>'
    )


def _svg_pie(labels, values) -> str:
    total = sum(v for v in values if v > 0)
    if total <= 0:
        return '<p class="empty">Pie charts need positive values.</p>'
    W, H = 760, 330
    cx, cy, r, ir = 175, H / 2, 125, 62
    a = -math.pi / 2
    slices, rows = [], []
    for i, (lab, v) in enumerate(zip(labels, values)):
        if v <= 0:
            continue
        frac = v / total
        a1 = a + frac * 2 * math.pi
        large = 1 if (a1 - a) > math.pi else 0
        x0, y0 = cx + r * math.cos(a), cy + r * math.sin(a)
        x1, y1 = cx + r * math.cos(a1), cy + r * math.sin(a1)
        ix0, iy0 = cx + ir * math.cos(a), cy + ir * math.sin(a)
        ix1, iy1 = cx + ir * math.cos(a1), cy + ir * math.sin(a1)
        colour = CHART_PALETTE[i % len(CHART_PALETTE)]
        d = (
            f"M {x0:.1f} {y0:.1f} A {r} {r} 0 {large} 1 {x1:.1f} {y1:.1f} "
            f"L {ix1:.1f} {iy1:.1f} A {ir} {ir} 0 {large} 0 {ix0:.1f} {iy0:.1f} Z"
        )
        slices.append(
            f'<path d="{d}" fill="{colour}" stroke="var(--panel)" '
            f'stroke-width="1.5"><title>{_e(lab)}: {_e(_fmt_num(v))} '
            f"({frac * 100:.1f}%)</title></path>"
        )
        ly = 34 + len(rows) * 25
        rows.append(
            f'<rect x="390" y="{ly - 9}" width="10" height="10" rx="2" fill="{colour}"/>'
            f'<text class="axis lgt" x="408" y="{ly}">{_e(_clip(lab, 30))}</text>'
            f'<text class="val" x="740" y="{ly}" text-anchor="end">'
            f"{_e(_fmt_num(v))} · {frac * 100:.1f}%</text>"
        )
        a = a1
    centre = (
        f'<text class="ctot" x="{cx}" y="{cy - 2}" text-anchor="middle">'
        f"{_e(_fmt_num(total))}</text>"
        f'<text class="axis" x="{cx}" y="{cy + 15}" text-anchor="middle">'
        f"TOTAL</text>"
    )
    return (
        f'<svg class="chart" viewBox="0 0 {W} {H}" role="img" '
        f'aria-label="Pie chart, {len(values)} slices">'
        f'{"".join(slices)}{centre}{"".join(rows)}</svg>'
    )


def _build_chart(rows, chart, label_column, value_columns, limit):
    """Returns (html, meta). Chooses sensible columns when none are given."""
    if not rows:
        return '<p class="empty">No rows to chart.</p>', {}

    numeric = _numeric_columns(rows)
    if not numeric:
        cols = ", ".join(_columns_of(rows)[:6])
        return (
            f'<p class="empty">No numeric column found. Columns seen: '
            f"{_e(cols)}.</p>",
            {"columns": _columns_of(rows)},
        )

    label_col = label_column if label_column in _columns_of(rows) else None
    if not label_col:
        label_col = _pick_label_column(rows, numeric)

    picked = [c for c in (value_columns or []) if c in numeric]
    if not picked:
        picked = [c for c in numeric if c != label_col] or numeric

    if chart == "pie":
        picked = picked[:1]
    else:
        picked = picked[:4]

    labels, series = _chart_series(rows, label_col, picked, limit)

    if chart == "auto":
        # Never auto-select pie: a pie asserts the values are parts of one whole,
        # which is false for prices, rates, or temperatures. Only honour it when
        # the user actually asks.
        chart = "line" if _looks_temporal(labels) else "bar"

    if chart == "pie":
        body = _svg_pie(labels, series[picked[0]])
    elif chart == "line":
        body = _svg_line(labels, series)
    else:
        body = _svg_bar(labels, series)

    if chart != "pie" and len(picked) > 1:
        body += _legend(picked)

    return body, {
        "chart": chart,
        "label_column": label_col,
        "value_columns": picked,
        "points": len(labels),
        "numeric_columns": numeric,
    }


