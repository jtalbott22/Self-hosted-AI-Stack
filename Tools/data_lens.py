_BUCKET_ORDER = ("Today", "This week", "This month", "This year", "Older")


def _published(h: dict) -> str:
    for k in ("publishedDate", "published_date", "pubdate", "date"):
        v = h.get(k)
        if v:
            return str(v)
    return ""


def _bucket(published: str) -> str:
    """Coarse recency bucket from a result's publish date."""
    s = (published or "").strip()
    if not s:
        return ""
    dt = None
    try:
        dt = datetime.fromisoformat(s.replace("Z", "+00:00"))
    except ValueError:
        for fmt in (
            "%Y-%m-%d %H:%M:%S",
            "%Y-%m-%d",
            "%a, %d %b %Y %H:%M:%S %z",
            "%d %b %Y",
            "%b %d, %Y",
        ):
            try:
                dt = datetime.strptime(s[:32].strip(), fmt)
                break
            except ValueError:
                continue
    if dt is None:
        return ""
    if dt.tzinfo is None:
        dt = dt.replace(tzinfo=timezone.utc)
    days = (datetime.now(timezone.utc) - dt).days
    if days < 1:
        return "Today"
    if days < 7:
        return "This week"
    if days < 31:
        return "This month"
    if days < 366:
        return "This year"
    return "Older"


def _item_attrs(host: str, bucket: str, text: str) -> str:
    """The data-* attributes the client-side filter reads."""
    return (
        f'data-item data-host="{_e(host)}" data-bucket="{_e(bucket)}" '
        f'data-text="{_e(text.lower())}"'
    )


def _facets(hits: list[dict]) -> tuple[list[tuple[str, int]], list[tuple[str, int]]]:
    hosts: dict[str, int] = {}
    buckets: dict[str, int] = {}
    for h in hits:
        ho = _host(h.get("url", ""))
        if ho:
            hosts[ho] = hosts.get(ho, 0) + 1
        b = _bucket(_published(h))
        if b:
            buckets[b] = buckets.get(b, 0) + 1
    top_hosts = sorted(hosts.items(), key=lambda kv: (-kv[1], kv[0]))[:10]
    ordered = [(b, buckets[b]) for b in _BUCKET_ORDER if b in buckets]
    return top_hosts, ordered


